//! 「その文字は絵文字か」の 1 実装（Issue #217 / #1536）
//!
//! tako の UI に絵文字は使わない（ユーザーの確定方針）。理由は 2 つで、
//! **安っぽく見える**ことと、**フォント依存で描画が揺れる**こと（同じ文字が
//! 環境によってカラー絵文字・白黒グリフ・豆腐のどれにもなる）。印が要る場所は
//! `gpui::svg()` に描画プリミティブ（パス・図形）を渡す
//! （アセットは `crates/tako-app/assets/icons/ui/`、定数は `file_icons::ui_icon`）。
//!
//! # なぜ tako-core に置くか
//!
//! 同じ判定を使う検査が **tako-app（`ui_text` のカタログ検査）と
//! tako-control（`crates/tako-app/src` を走査する番犬 `issue1536_no_emoji_ui_watchdog`）の
//! 両方**にある。判定を 2 つ持つと、片方だけ範囲を広げたときに
//! 「片方は緑・片方は赤」になって、どちらが正かが分からなくなる。
//! `source_scan`（#1496）と同じ理由で、両方が依存する tako-core に 1 本だけ置く。
//!
//! # 何を絵文字とするか
//!
//! Unicode の **Emoji プロパティ**（`emoji-data.txt` の `Emoji=Yes`）を採る。
//! 「既定でカラー絵文字として描かれる」（`Emoji_Presentation=Yes`）より広いのは、
//! `⬆`（U+2B06）や `↔`（U+2194）のように**既定はテキストでも環境やフォント次第で
//! 絵文字になる**文字が実際に揺れるため。逆に `×`（U+00D7）・`●`（U+25CF）・
//! `→`（U+2192）のような**純粋なテキスト記号は対象外**（Emoji プロパティを持たない）。
//!
//! 範囲は BMP 側を明示の表で、SMP 側（絵文字ブロック）を 1 つの範囲で持つ。
//!
//! **ブロック単位で広めに採っている所が 2 つある**（意図的な過剰検出）:
//! U+1F000〜U+1FAFF には麻雀牌やトランプが、U+2600〜U+27BF（その他の記号 +
//! 装飾記号）には `❯`（U+276F）のように Emoji プロパティを持たない文字が混じる。
//! どちらも **UI に置く理由が無い**うえ、この 2 ブロックは
//! `ui_text` のカタログ検査（#217）が最初から丸ごと禁じていた範囲なので、
//! 狭めずに揃える。`❯` は claude TUI の画面を再現する検査データにだけ出るので、
//! 走査側（番犬）の許可リストで理由つきに通す。

/// Emoji プロパティを持つ単独のコードポイント（BMP 側）
const SINGLES: &[u32] = &[
    0x00A9, // ©
    0x00AE, // ®
    0x203C, // ‼
    0x2049, // ⁉
    0x2122, // ™
    0x2139, // ℹ
    0x2328, // ⌨
    0x23CF, // ⏏
    0x24C2, // Ⓜ
    0x25B6, // ▶
    0x25C0, // ◀
    0x3030, // 〰
    0x303D, // 〽
    0x3297, // ㊗
    0x3299, // ㊙
    0xFE0F, // 異体字セレクタ 16（絵文字表示を強制する）
];

/// Emoji プロパティを持つコードポイントの範囲（両端を含む）
const RANGES: &[(u32, u32)] = &[
    (0x1F000, 0x1FAFF), // 絵文字ブロック（SMP 側）
    (0x2194, 0x2199),   // ↔↕↖↗↘↙
    (0x21A9, 0x21AA),   // ↩↪
    (0x231A, 0x231B),   // ⌚⌛
    (0x23E9, 0x23FA),   // ⏩〜⏺（メディア操作・時計）
    (0x25AA, 0x25AB),   // ▪▫
    (0x25FB, 0x25FE),   // ◻◼◽◾
    (0x2600, 0x27BF),   // その他の記号 + 装飾記号（☀☕✅✔✕✨➜ 等）
    (0x2934, 0x2935),   // ⤴⤵
    (0x2B00, 0x2BFF),   // その他の記号と矢印（⬅⬆⬇⭐⬛ 等）
];

/// 絵文字として描かれうる文字か（UI に置いてはいけない文字か）。
///
/// **`U+FE0E`（テキスト表示を強制する異体字セレクタ）は絵文字ではない**。
/// 絵文字化を防ぐ側の文字なので、対象に含めない
pub fn is_emoji(c: char) -> bool {
    let cp = c as u32;
    SINGLES.contains(&cp) || RANGES.iter().any(|&(lo, hi)| (lo..=hi).contains(&cp))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 方針で名指しされている絵文字はすべて拾う() {
        // Issue #1536 が挙げた文字 + 実際に置換したもの
        for c in [
            '☕', '🌐', '📌', '⏏', '✓', '✕', '▶', '⬆', '↔', '🎉', '✅', '⚠',
        ] {
            assert!(is_emoji(c), "{c:?} (U+{:04X}) を拾えていない", c as u32);
        }
    }

    #[test]
    fn 純粋なテキスト記号は対象外() {
        // 罫線・約物・矢印（U+2192 系）・乗算記号は絵文字にならないので通す。
        // ここを広げると本文（コメント・案内文）まで書けなくなる
        for c in [
            '×', '●', '→', '←', '↑', '↓', '…', '·', '—', '⎿', '─', '│', '╭', '⎇', '⠿', '√', '▸',
            '▾', '\u{FE0E}',
        ] {
            assert!(
                !is_emoji(c),
                "{c:?} (U+{:04X}) を誤って拾っている",
                c as u32
            );
        }
    }

    /// ブロック単位で採っているぶん、Emoji プロパティを持たない文字も落ちる。
    /// **意図した過剰検出**なので、狭める変更が入ったらここで気づく
    #[test]
    fn ブロックごと採っている範囲は過剰検出を認める() {
        for c in ['❯', '✻', '✽', '⏺', '⏵'] {
            assert!(is_emoji(c), "{c:?} (U+{:04X}) は範囲ごと拾う側", c as u32);
        }
    }

    #[test]
    fn 範囲の境界を跨がない() {
        assert!(!is_emoji('\u{2193}')); // ↓ = U+2193（範囲の 1 つ手前）
        assert!(is_emoji('\u{2194}')); // ↔ = U+2194（範囲の先頭）
        assert!(is_emoji('\u{2199}')); // ↙ = U+2199（範囲の末尾）
        assert!(!is_emoji('\u{219A}')); // ↚ = U+219A（範囲の 1 つ後ろ）
        assert!(!is_emoji('\u{25FF}')); // ◿ = U+25FF
        assert!(is_emoji('\u{1FAFF}'));
        assert!(!is_emoji('\u{1FB00}'));
    }
}
